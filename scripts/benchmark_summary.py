"""
benchmark_summary.py — Aggregate all results/*.json files into a
                        markdown and CSV benchmark table.

Usage:
    python scripts/benchmark_summary.py --results_dir results/ --out results/BENCHMARK.md

Output:
    - results/BENCHMARK.md   — github-flavoured markdown table
    - results/BENCHMARK.csv  — machine-readable CSV
"""

import argparse
import json
import csv
import sys
from pathlib import Path


# Metrics we care about, in display order
METRIC_COLS = ["accuracy", "roc_auc", "average_precision", "f1", "brier_score", "optimal_threshold"]
DISPLAY_NAMES = {
    "accuracy": "Accuracy",
    "roc_auc": "ROC-AUC",
    "average_precision": "Avg Precision",
    "f1": "F1",
    "brier_score": "Brier ↓",
    "optimal_threshold": "Threshold",
}


def load_metric_jsons(results_dir: Path) -> list[dict]:
    """
    Scan results_dir for *_metrics.json files and parse them.
    Returns a list of row dicts sorted by dataset name.
    """
    rows = []
    for p in sorted(results_dir.glob("**/*_metrics.json")):
        try:
            with open(p) as f:
                data = json.load(f)
        except (json.JSONDecodeError, OSError) as e:
            print(f"  [warn] skipping {p.name}: {e}", file=sys.stderr)
            continue

        row = {"dataset": data.get("dataset", p.stem.replace("_metrics", ""))}
        for col in METRIC_COLS:
            val = data.get(col)
            if val is None:
                row[col] = "—"
            elif col == "optimal_threshold":
                row[col] = f"{val:.3f}"
            else:
                row[col] = f"{val:.4f}"
        row["n_samples"] = data.get("num_samples", "?")
        row["_source"] = str(p.relative_to(results_dir))
        rows.append(row)

    return rows


def render_markdown(rows: list[dict]) -> str:
    """Render rows as a github-flavoured markdown table."""
    all_cols = ["Dataset", "N"] + [DISPLAY_NAMES[c] for c in METRIC_COLS] + ["Source"]
    sep = ["---"] * len(all_cols)

    lines = ["| " + " | ".join(all_cols) + " |", "| " + " | ".join(sep) + " |"]
    for r in rows:
        cells = [
            r["dataset"],
            str(r["n_samples"]),
            *[r[c] for c in METRIC_COLS],
            r["_source"],
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_csv(rows: list[dict], out_path: Path):
    """Write rows to CSV."""
    fieldnames = ["dataset", "n_samples"] + METRIC_COLS + ["_source"]
    with open(out_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser(description="Aggregate DeepTrace benchmark results into a summary table.")
    parser.add_argument("--results_dir", type=str, default="results/", help="Directory containing *_metrics.json files.")
    parser.add_argument("--out", type=str, default="results/BENCHMARK.md", help="Output markdown file path.")
    args = parser.parse_args()

    results_dir = Path(args.results_dir)
    if not results_dir.exists():
        print(f"[error] results_dir not found: {results_dir}", file=sys.stderr)
        sys.exit(1)

    rows = load_metric_jsons(results_dir)
    if not rows:
        print("[warn] No *_metrics.json files found. Nothing to summarise.", file=sys.stderr)
        sys.exit(0)

    print(f"[benchmark_summary] Found {len(rows)} result file(s).")

    md = render_markdown(rows)

    out_md = Path(args.out)
    out_md.parent.mkdir(parents=True, exist_ok=True)

    header = (
        "# DeepTrace Benchmark Summary\n\n"
        "> Auto-generated by `scripts/benchmark_summary.py`. "
        "Do not edit manually — re-run the script to refresh.\n\n"
    )
    out_md.write_text(header + md + "\n", encoding="utf-8")
    print(f"[benchmark_summary] Markdown written to {out_md}")

    out_csv = out_md.with_suffix(".csv")
    render_csv(rows, out_csv)
    print(f"[benchmark_summary] CSV written to {out_csv}")


if __name__ == "__main__":
    main()
